UNITY_STORE_DIR = os.getenv("OG_UNITY_STORE_DIR", "unity_builds")
_PENDING_TTL = 60 * 60          # a plan/preview stays approvable 1 h
_ZIP_TTL = 24 * 60 * 60         # packaged ZIPs are kept 24 h
_MAX_FILES = 40
_MAX_FILE_BYTES = 64 * 1024
_MAX_TOTAL_BYTES = 512 * 1024
_ALLOWED_EXTS = (".cs", ".md", ".txt", ".json", ".asmdef")
_ALLOWED_ROOTS = ("Assets/", "ProjectSettings/", "Packages/")
_UNITY_VERSION = "2022.3.45f1"  # Unity 2022.3 LTS

_HONESTY_LINES = (
    "This project was generated by an AI and has NOT been compiled "
    "or tested in Unity. Art is placeholder (code-drawn primitives) "
    "unless you add your own assets.")

# Bound by app.py via bind_app (the visitor-history reader the
