"""
OG Unity maker (Round 16) — OG builds downloadable Unity projects
for visitors, under Brent's approval flow (prepare -> approve ->
execute, the same rule as the Round 14 GitHub PR flow).

The flow, all inside the visitor's own chat thread:

1. ASK -> PLAN GATE. "make me a Unity game ..." claims a Unity job.
   OG answers with a plain-language PLAN only (what it is, the
   pieces/scripts, the controls, what's placeholder) ending in an
   explicit approval ask. A per-visitor pending state {stage: plan}
   is parked (60-minute expiry). NO cancels, tweaking the plan
   re-plans, drifting to another topic abandons the plan.
2. BUILD DRAFT. On YES, an instruction riding the established
   app-layer search seam (persona files are NEVER touched) makes the
   agent generate the whole project in-chat as strict file blocks:

       === PROJECT: <Name> ===
       === FILE: Assets/Scripts/PlayerController.cs ===
       <full file content>
       === END FILE ===

   and present a PREVIEW section (the file list + the honesty note)
   ending in "Reply YES to package it". Stage moves to preview.
   Change requests ("make the player faster") loop right here: the
   agent regenerates the full file set with the change applied and
   the preview is shown again. NOTHING is zipped at this stage.
3. PACKAGE ON APPROVAL. On the preview YES the module lifts the file
   blocks out of the visitor's OWN history (the Round 14 pattern —
   what was shown is what ships), validates and sanitizes them,
   writes the README itself (project name, "Generated by OG AI",
   Unity 2022.3 LTS target, open-in-Unity steps, and the honesty
   lines: AI-generated, NOT compiled or tested, placeholder art),
   guarantees ProjectSettings/ProjectVersion.txt (2022.3 LTS) and a
   minimal Packages/manifest.json when the draft lacks them, and
   zips. Only a successful package spends one unit of the per-tier
   "unity" cap (og_tiers kind "unity": free 1 / standard 3 / pro 10
   / blue 25 / blackout 100 per day). Plans, previews, revisions,
   declines and failures spend nothing; an at-cap visitor is told at
   the ASK stage. The ZIP is stored per-visitor for 24 h and served
   only to the owning ogai_uid cookie at GET /unity/download/<id>.
4. REVISIONS AFTER DOWNLOAD re-enter the preview loop from the
   packaged state: a fix ask regenerates the file set, the preview
   shows again, and a YES packages a NEW ZIP (a new version, one
   more unit).

Validation (fail safe — nothing packaged, nothing charged):
paths are sanitized (no "..", no absolute paths; files must live
under Assets/, ProjectSettings/ or Packages/, plus README.md at the
root — the module's own README always wins); extensions are
allowlisted (.cs .md .txt .json .asmdef); caps are <=40 files,
<=64 KB per file, <=512 KB total. Individual bad files are dropped;
zero valid files (or a total-size breach) packages nothing.

Pending state is process-local (like the Round 14 PR drafts): a
server restart inside the window drops an unapproved draft —
nothing was packaged, by design; the visitor just asks again.
"""

