_deps: Dict = {}


def bind_app(deps):
    _deps.update(deps)


def _pro_url() -> str:
    base = os.getenv("OG_PUBLIC_URL", "https://og-ai-service.onrender.com")
    return base.rstrip("/") + "/pro"


# --- Pending build state (approval-gate state) --------------------------------
# One pending Unity build per visitor, process memory, hard expiry —
# the Round 14 pending-draft shape with one more stage.

_pending_builds: Dict[str, Dict] = {}
_pending_lock = threading.Lock()


def _set_pending(uid: str, state: Dict):
    state = dict(state)
    state["created"] = time.time()
    with _pending_lock:
        _pending_builds[uid] = state


def _get_pending(uid: str) -> Optional[Dict]:
    if not uid:
        return None
    with _pending_lock:
        state = _pending_builds.get(uid)
        if state and time.time() - float(state.get("created", 0)) \
                > _PENDING_TTL:
            del _pending_builds[uid]
            return None
        return dict(state) if state else None


def _clear_pending(uid: str):
    with _pending_lock:
        _pending_builds.pop(uid, None)


# --- Intent parsing -------------------------------------------------------------
# Deliberately narrow: a Unity ask needs the word "unity" plus a
# build verb (or want/give phrasing). Questions ABOUT Unity ("what
# is unity", "unity vs unreal") match nothing and flow to normal
# chat exactly as before.

_BUILD_VERB = (r"(?:make|build|create|generate|code|write|design|"
               r"develop)")
_ASK_RES = (
    r"\b" + _BUILD_VERB + r"\b[^.?!]{0,60}\bunity\b",
    r"\bunity\b[^.?!]{0,40}\b(game|project|app|prototype)\b[^.?!]{0,30}"
    r"\b" + _BUILD_VERB + r"\b",
    r"\b(?:i want|i need|give me|get me)\b[^.?!]{0,40}\bunity\b",
    r"\b" + _BUILD_VERB + r"\b[^.?!]{0,30}\ba unity\b",
)
_APPROVE_RE = re.compile(
    r"^\W*(yes|yeah|yep|yup|approve|approved|go ahead|do it|ship it"
    r"|confirm|ok|okay|package it|sounds good|let'?s go)\b")
_DECLINE_RE = re.compile(
    r"^\W*(no|nope|nah|cancel|scrap|discard|never ?mind|stop|don'?t"
    r"|do not)\b")
_REVISE_MARKERS = (
    "change", "add", "remove", "fix", "make", "faster", "slower",
    "bigger", "smaller", "instead", "replace", "update", "rename",
    "color", "colour", "speed", "jump", "also", "more", "less",
    "tweak", "adjust", "different", "increase", "decrease", "swap",
    "switch", "rather", "prefer", "but",
)
_PLAN_TWEAK_MARKERS = (
    "change", "add", "remove", "instead", "switch", "rather",
    "prefer", "make it", "turn it", "2d", "3d", "drop",
)


def _has_markers(low: str, markers) -> bool:
    return any(m in low for m in markers)


def parse_unity_intent(message: str) -> Optional[Dict]:
    """A fresh Unity build ask, or None."""
    low = " " + re.sub(r"\s+", " ", str(message).lower()).strip() + " "
    for pattern in _ASK_RES:
        if re.search(pattern, low):
            return {"kind": "ask", "request": str(message).strip()}
    return None


def _claim_job(message: str, uid: str) -> Optional[Dict]:
    """What this message means for the Unity maker, given the
    visitor's pending state. Approvals/declines only count against
    a live pending build; change requests only claim when they
    carry change language, so unrelated chat is never hijacked."""
    low = " " + re.sub(r"\s+", " ", str(message).lower()).strip() + " "
    trimmed = low.strip()
    pending = _get_pending(uid)
    fresh = parse_unity_intent(message)

    if pending is None:
        return fresh

    stage = pending.get("stage", "")
    decline = bool(_DECLINE_RE.match(trimmed))
    approve = bool(_APPROVE_RE.match(trimmed))
    revise = _has_markers(trimmed, _REVISE_MARKERS)

    if stage == "plan":
        if decline and not revise:
            return {"kind": "plan_decline"}
        if fresh:
            return fresh
        if approve and not _has_markers(trimmed, _PLAN_TWEAK_MARKERS):
            return {"kind": "plan_approve"}
        if _has_markers(trimmed, _PLAN_TWEAK_MARKERS):
            return {"kind": "plan_revise"}
        # New topic: the plan is abandoned, chat flows on untouched.
        _clear_pending(uid)
        return None

    if stage == "preview":
        if decline and not revise:
            return {"kind": "preview_decline"}
        if fresh:
            return fresh
        if approve and not revise:
            return {"kind": "preview_approve"}
        if revise:
            return {"kind": "revise"}
        return None  # unrelated chat; the draft stays parked

    if stage == "done":
        if fresh:
            return fresh
        if revise or "unity" in trimmed:
            return {"kind": "revise"}
        return None

    return fresh


# --- Instruction results (the seam's {title, body, href} shape) -----------------

def _result(tag: str, title: str, body: str, href: str = "") -> list:
    return [{"title": title, "body": f"[{tag}] " + body, "href": href}]


