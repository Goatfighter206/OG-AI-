def register_unity_routes(app):
    """Attach GET /unity/download/<id> — the packaged ZIP, served
    only to the visitor who owns it (their ogai_uid cookie), only
    inside the 24 h retention window."""

    @app.get("/unity/download/{build_id}")
    async def unity_download(build_id: str, raw_request: Request):
        if not re.fullmatch(r"[0-9a-f]{32}", build_id or ""):
            raise HTTPException(status_code=404, detail="Not found")
        zpath = os.path.join(UNITY_STORE_DIR, build_id + ".zip")
        mpath = os.path.join(UNITY_STORE_DIR, build_id + ".json")
        if not os.path.exists(zpath) or not os.path.exists(mpath):
            raise HTTPException(status_code=404, detail="Not found")
        if time.time() - os.path.getmtime(zpath) > _ZIP_TTL:
            raise HTTPException(status_code=404, detail="Not found")
        import json
        try:
            with open(mpath) as f:
                meta = json.load(f)
        except Exception:
            raise HTTPException(status_code=404, detail="Not found")
        uid = raw_request.cookies.get("ogai_uid")
        if not uid or meta.get("uid") != uid:
            raise HTTPException(status_code=404, detail="Not found")
        return FileResponse(
            zpath, media_type="application/zip",
            filename=meta.get("filename", "unity-project.zip"))
