# The Unity job parsed for the exchange currently being processed.
# All chat processing is serialized under app.py's _memory_lock, so
# a single slot is safe — the same reasoning as app.py's own slots.
_pending = {"job": None, "message": ""}


def install_unity_tools(agent_instance, get_uid, consume_unity,
                        unity_left):
    """Wrap the agent's detect_intent + web_search hooks so Unity
    build asks and the approval flow ride the established seam.
    get_uid() returns the current visitor's uid; consume_unity(uid)
    spends one unit of the per-tier unity cap (False at cap);
    unity_left(uid) reports units left today. Claimed jobs also
    clear needs_code_generation — the agent's own code generator
    would otherwise hijack "make me a ..." asks before the search
    seam ever fires. Non-Unity messages pass through untouched.
    Persona files never touched."""
    if getattr(agent_instance, "_og_unity_installed", False):
        return
    prev_detect = getattr(agent_instance, "detect_intent", None)
    prev_search = getattr(agent_instance, "web_search", None)
    if prev_detect is None or prev_search is None:
        return

    def detect_wrapped(message):
        intent = prev_detect(message)
        _pending["job"] = None
        _pending["message"] = ""
        try:
            uid = get_uid()
            job = _claim_job(str(message), uid) if uid else None
            if job:
                _pending["job"] = job
                _pending["message"] = str(message)
                if isinstance(intent, dict):
                    intent["needs_code_generation"] = False
                    if not intent.get("needs_web_search"):
                        intent["needs_web_search"] = True
                        intent["search_query"] = str(message).strip()
        except Exception as e:
            logger.warning(f"Unity trigger check failed: {e}")
            _pending["job"] = None
        return intent

    def search_wrapped(query, num_results=5):
        job = _pending.get("job")
        message = _pending.get("message", "")
        _pending["job"] = None
        _pending["message"] = ""
        if job:
            try:
                results = unity_results(
                    job, message, get_uid(), consume_unity,
                    unity_left)
            except Exception as e:
                logger.warning(f"Unity job failed: {e}")
                results = None
            if results:
                return results[: max(1, num_results)]
        return prev_search(query, num_results)

    agent_instance.detect_intent = detect_wrapped
    agent_instance.web_search = search_wrapped
    agent_instance._og_unity_installed = True


