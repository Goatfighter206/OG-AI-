def _declined_body(what: str) -> list:
    body = (f"The visitor said NO to the Unity {what}. It is "
            "SCRAPPED — nothing was built or packaged and nothing "
            "was charged. Confirm that to them in persona, briefly, "
            "and let them know they can ask for a different build "
            "any time.")
    return _result("UNITY-MAKER: DECLINED", "🎮 Unity maker — scrapped",
                   body)


def _cap_body(left_note: str) -> list:
    body = (f"The visitor wants a Unity project built, but they've "
            f"used up today's Unity project allowance for their "
            f"plan ({left_note}). Do NOT plan or build anything. "
            f"Tell them plainly, in persona, that the allowance "
            f"resets tomorrow — or that higher plans build more: "
            f"{_pro_url()}")
    return _result("UNITY-MAKER: CAP", "🎮 Unity maker — daily cap",
                   body, _pro_url())


# --- File-block extraction + validation ------------------------------------------

_FILE_BLOCK_RE = re.compile(
    r"^===\s*FILE:\s*(.+?)\s*===\s*$\n(.*?)^===\s*END FILE\s*===\s*$",
    re.S | re.M)
_PROJECT_RE = re.compile(r"===\s*PROJECT:\s*(.+?)\s*===", re.I)


def _extract_generation(uid: str):
    """Lift the latest generation out of the visitor's own thread:
    the newest assistant message carrying FILE blocks. Returns
    (project_name, {path: content}) or (None, {})."""
    load_history = _deps.get("load_history")
    if load_history is None:
        return None, {}
    try:
        history = load_history(uid)
    except Exception as e:
        logger.warning(f"Unity history read failed: {e}")
        return None, {}
    for entry in reversed(history or []):
        if not isinstance(entry, dict) \
                or entry.get("role") != "assistant":
            continue
        text = str(entry.get("content", ""))
        if "=== FILE:" not in text:
            continue
        files = {}
        for m in _FILE_BLOCK_RE.finditer(text):
            files[m.group(1).strip()] = m.group(2)
        if not files:
            return None, {}
        name = None
        m_name = _PROJECT_RE.search(text)
        if m_name:
            name = re.sub(r"[^\w\- ]+", "", m_name.group(1)).strip()[:60]
        return name or None, files
    return None, {}


def _sanitize_path(raw: str) -> Optional[str]:
    """A safe project-relative path, or None when the file must be
    dropped: no traversal, no absolute paths, allowlisted roots
    and extensions only."""
    path = str(raw or "").strip().replace("\\", "/")
    path = path.lstrip("/")
    if not path or len(path) > 200:
        return None
    parts = path.split("/")
    if any(p in ("", ".", "..") for p in parts):
        return None
    if not path.lower().endswith(_ALLOWED_EXTS):
        return None
    if path == "README.md":
        return path
    if not any(path.startswith(root) for root in _ALLOWED_ROOTS):
        return None
    return path


def _validate_files(raw_files: Dict) -> Optional[Dict]:
    """Sanitize + cap the extracted draft. Individual bad files
    are dropped; returns the clean {path: content} or None when
    nothing valid remains or the total-size cap is breached."""
    clean: Dict[str, str] = {}
    total = 0
    for raw_path, content in raw_files.items():
        path = _sanitize_path(raw_path)
        if path is None or path in clean:
            continue
        data = str(content).encode("utf-8")
        if len(data) > _MAX_FILE_BYTES:
            continue
        clean[path] = str(content)
        total += len(data)
        if len(clean) > _MAX_FILES or total > _MAX_TOTAL_BYTES:
            return None
    return clean or None


# --- Packaging ---------------------------------------------------------------------

def _readme_text(name: str, files: Dict) -> str:
    listing = "\n".join(
        f"- {p} ({len(c.encode('utf-8'))} bytes)"
        for p, c in sorted(files.items()))
    return (
        f"# {name}\n\n"
        "Generated by OG AI (the OG Unity maker), from a chat "
        "request, and approved by the requester before packaging.\n\n"
        "## Honesty note\n\n"
        + _HONESTY_LINES + "\n\n"
        "## Open it in Unity\n\n"
        "1. Install Unity Hub and Unity 2022.3 LTS (this project "
        "targets Unity 2022.3 LTS — see "
        "ProjectSettings/ProjectVersion.txt).\n"
        "2. Unzip this file and open the unzipped folder in "
        "Unity Hub (Open -> Add project from disk).\n"
        "3. Let Unity import. There is no prebuilt scene file: "
        "the bootstrap script under Assets/Scripts builds the "
        "scene in code — create an empty scene (or open any "
        "scene), and press Play; the bootstrap runs on load. If "
        "the README inside Assets says otherwise, follow the "
        "bootstrap script's own header comment.\n"
        "4. Swap the placeholder primitives for your own art "
        "when you're ready — the scripts mark the spots.\n\n"
        "## Files\n\n" + listing + "\n")


def _sweep_old_zips():
    try:
        now = time.time()
        for fname in os.listdir(UNITY_STORE_DIR):
            if not fname.endswith(".zip"):
                continue
            fpath = os.path.join(UNITY_STORE_DIR, fname)
            if now - os.path.getmtime(fpath) > _ZIP_TTL:
                try:
                    os.remove(fpath)
                    meta = fpath[:-4] + ".json"
                    if os.path.exists(meta):
                        os.remove(meta)
                except OSError:
                    pass
    except OSError:
        pass


def _package(uid: str, name: str, files: Dict) -> Optional[Dict]:
    """Zip the validated draft (module README + guaranteed project
    files). Returns {id, filename, size, files} or None."""
    files = dict(files)
    files.pop("README.md", None)
    if "ProjectSettings/ProjectVersion.txt" not in files:
        files["ProjectSettings/ProjectVersion.txt"] = (
            f"m_EditorVersion: {_UNITY_VERSION}\n"
            f"m_EditorVersionWithRevision: {_UNITY_VERSION}\n")
    if "Packages/manifest.json" not in files:
        files["Packages/manifest.json"] = (
            '{\n  "dependencies": {\n    "com.unity.ugui": "1.0.0"\n'
            "  }\n}\n")
    files["README.md"] = _readme_text(name, files)
    try:
        os.makedirs(UNITY_STORE_DIR, exist_ok=True)
        _sweep_old_zips()
        build_id = uuid.uuid4().hex
        slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:40] \
            or "unity-project"
        filename = f"{slug}.zip"
        zpath = os.path.join(UNITY_STORE_DIR, build_id + ".zip")
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as zf:
            for path in sorted(files):
                zf.writestr(path, files[path])
        import json
        meta = {"uid": uid, "name": name, "filename": filename,
                "created": datetime.now(timezone.utc).isoformat(),
                "files": sorted(files)}
        with open(os.path.join(UNITY_STORE_DIR, build_id + ".json"),
                  "w") as f:
            json.dump(meta, f)
        return {"id": build_id, "filename": filename,
                "size": os.path.getsize(zpath), "files": sorted(files)}
    except Exception as e:
        logger.warning(f"Unity packaging failed: {e}")
        return None


# --- Execution -----------------------------------------------------------------------

def unity_results(job, message, uid, consume_unity, unity_left):
    """Run one claimed Unity job. Returns web_search-shaped results
    (plan / generation / revision instructions, or the module's own
    packaging outcome), or None on a true miss so the caller falls
    through to the previous search untouched. Only a successful
    package spends a unity unit — via app.py's consume_unity."""
    if not job or not uid:
        return None
    kind = job.get("kind", "")

    if kind == "ask":
        left = None
        try:
            left = unity_left(uid) if unity_left else None
        except Exception as e:
            logger.warning(f"Unity cap check failed: {e}")
        if left is not None and left <= 0:
            return _cap_body("0 left today")
        _set_pending(uid, {"stage": "plan",
                            "request": job.get("request", "")})
        return _plan_body(job.get("request", ""))

    pending = _get_pending(uid)
    if pending is None:
        return None  # expired between claim and execution — not ours
    request = pending.get("request", "")

    if kind == "plan_decline":
        _clear_pending(uid)
        return _declined_body("plan")

    if kind == "preview_decline":
        _clear_pending(uid)
        return _declined_body("draft")

    if kind == "plan_revise":
        return _plan_body(request, revised=True)

    if kind == "plan_approve":
        _set_pending(uid, {"stage": "preview", "request": request})
        return _generate_body(request)

    if kind == "revise":
        _set_pending(uid, {"stage": "preview", "request": request,
                           "name": pending.get("name", "")})
        return _generate_body(request, change=str(message).strip())

    if kind == "preview_approve":
        name, raw_files = _extract_generation(uid)
        files = _validate_files(raw_files) if raw_files else None
        if not files:
            _clear_pending(uid)
            body = (
                "The visitor approved the Unity draft, but OG "
                "could NOT package it: the generated files in the "
                "thread didn't pass validation (missing, unsafe "
                "paths, or over the size caps). NOTHING was "
                "packaged and NOTHING was charged. Tell them "
                "plainly, in persona, and invite them to ask for "
                "the build again so a fresh draft is generated.")
            return _result("UNITY-MAKER: PACKAGE-FAILED",
                           "🎮 Unity maker — packaging stopped", body)
        name = name or pending.get("name") or "Unity Project"
        packed = _package(uid, name, files)
        if packed is None:
            _clear_pending(uid)
            body = (
                "The visitor approved the Unity draft, but the "
                "ZIP itself failed to build. NOTHING was packaged "
                "and NOTHING was charged. Tell them plainly, in "
                "persona, and invite them to ask again.")
            return _result("UNITY-MAKER: PACKAGE-FAILED",
                           "🎮 Unity maker — packaging stopped", body)
        spent = True
        if consume_unity is not None:
            try:
                spent = bool(consume_unity(uid))
            except Exception as e:
                logger.warning(f"Unity consume failed: {e}")
                spent = False
        if not spent:
            # Cap raced us — remove the ZIP, charge nothing, and
            # say so (the unit is only ever spent on success).
            try:
                os.remove(os.path.join(
                    UNITY_STORE_DIR, packed["id"] + ".zip"))
                os.remove(os.path.join(
                    UNITY_STORE_DIR, packed["id"] + ".json"))
            except OSError:
                pass
            _clear_pending(uid)
            return _cap_body("the last unit just went to another "
                             "build")
        _set_pending(uid, {"stage": "done", "request": request,
                           "name": name, "zip_id": packed["id"]})
        link = f"/unity/download/{packed['id']}"
        listing = ", ".join(packed["files"])
        body = (
            f"DONE — the Unity project the visitor approved is "
            f"PACKAGED: \"{name}\" ({len(packed['files'])} files, "
            f"{packed['size']} bytes zipped). Files: {listing}. "
            f"The download link is {link} — give them that exact "
            f"link, in persona. It works for 24 hours and only "
            f"from their browser. Remind them briefly: unzip, "
            f"open the folder in Unity Hub with Unity 2022.3 LTS, "
            f"press Play — and that it was AI-generated and not "
            f"compiled or tested, art is placeholder. If they "
            f"want changes after trying it, tell them to just ask "
            f"— fixes go through the same preview + YES flow and "
            f"ship as a new ZIP.")
        return _result("UNITY-MAKER: PACKAGED",
                       "🎮 Unity maker — packaged", body, link)

    return None


