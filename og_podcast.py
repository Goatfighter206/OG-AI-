                pending_view = {
                    "stage": pending.get("stage", "await_capture"),
                    "title": pending.get("topic", ""),
                    "voices": pending.get("voices", []),
                    "lines": 0, "words": 0, "est_min": 0,
                    "tts_est": 0, "preview": "",
                    "expires_in_s": max(0, expires)}
