# --- Usage / caps (the usage store, app.py's own shapes) -------------------------


def _today() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def _usage_get(key: str):
    load, lock = _dep("load_usage"), _dep("usage_lock")
    if load is None or lock is None:
        return None
    with lock:
        store = load()
    entry = store.get(key)
    return dict(entry) if isinstance(entry, dict) else None


def _tts_used_week(uid: str) -> int:
    return _tiers.week_used(_usage_get(f"tts:{uid}"))


def _tts_week_left(uid: str, tier: str) -> int:
    cap_w = _tiers.weekly_cap(tier, "tts")
    if cap_w is None:
        return 0
    return max(0, int(cap_w) - _tts_used_week(uid))


_local_tts_counts: Dict[str, int] = {}


def _record_tts_call(uid: str) -> int:
    """Record ONE tts call for `uid`, in the exact entry shape
    app.py's _consume_tts_call writes ("tts:<uid>", carry_days +
    note_day substrate). Deliberately NOT cap-refusing: inside
    an approved podcast job the episode finishes even past the
    weekly pool (see the module docstring). Returns the caller's
    new weekly tts total. When the usage store is unbound (unit
    seams), a process-local counter keeps the accounting
    observable instead of silently dropping it."""
    load, save, lock = (_dep("load_usage"), _dep("save_usage"),
                        _dep("usage_lock"))
    if load is None or save is None or lock is None:
        _local_tts_counts[uid] = _local_tts_counts.get(uid, 0) + 1
        return _local_tts_counts[uid]
    key = f"tts:{uid}"
    with lock:
        store = load()
        entry = store.get(key)
        if not isinstance(entry, dict) or entry.get("date") != _today():
            old, entry = entry, {"date": _today(), "count": 0}
            _tiers.carry_days(old, entry)
        entry["count"] = int(entry.get("count", 0)) + 1
        _tiers.note_day(entry, _today(), entry["count"])
        store[key] = entry
        save(store)
        return _tiers.week_used(entry)


