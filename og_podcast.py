            pending = _ensure_captured(uid, pending) or pending
            expires = int(float(pending.get("created", time.time()))
                          + _PENDING_TTL - time.time())
            if pending.get("lines"):
                script = {"lines": pending["lines"],
                          "words": pending.get("words", 0)}
                pending_view = {
                    "stage": "await_approval",
                    "title": pending.get("title", ""),
                    "voices": pending.get("voices", []),
                    "lines": len(pending["lines"]),
                    "words": int(pending.get("words", 0)),
                    "est_min": _est_min(pending.get("words", 0)),
                    "tts_est": estimate_tts_calls(script),
                    "preview": "\n".join(
                        f"HOST {ln['host']}: {ln['text']}"
                        for ln in pending["lines"][:4]),
                    "expires_in_s": max(0, expires)}
