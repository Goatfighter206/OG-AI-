def _new_job(uid: str, pending: Dict) -> Dict:
    job_id = uuid.uuid4().hex[:16]
    script = {"title": pending.get("title", "OG's Podcast"),
              "lines": pending.get("lines", []),
              "words": pending.get("words", 0),
              "voices": pending.get("voices")
              or list(DEFAULT_VOICES)}
    est = estimate_tts_calls(script)
    tier = _tier_now(uid)
    left = _tts_week_left(uid, tier)
    return {
        "id": job_id, "owner": _key(uid),
        "title": script["title"],
        "topic": pending.get("topic", ""),
        "voices": script["voices"],
        "script": script,
        "line_count": len(script["lines"]),
        "words": script["words"],
        "tts_est": est,
        "tts_calls": 0,
        # Estimated calls past the weekly pool at approval time;
        # the actual overage is recomputed when the job lands.
        "tts_overage_est": max(0, est - left),
        "tts_overage": 0,
        "state": "queued", "detail": "In line — booth starting.",
        "created": time.time(), "updated": time.time(),
        "file": "", "size": 0, "duration": 0.0,
        "saved": False, "charged": False, "error": "",
    }


def _update(rec: Dict, **kw) -> Dict:
    rec.update(kw)
    rec["updated"] = time.time()
    _store_put(rec)
    return rec


