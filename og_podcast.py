class _TTSError(Exception):
    def __init__(self, kind: str, message: str):
        super().__init__(message)
        self.kind = kind


def _synth_line(text: str, voice: str) -> bytes:
    """ONE TTS call: POST one <=600-char chunk to the same
    OpenAI speech endpoint /tts uses, in `voice`; return the
    MP3 bytes. Raises _TTSError on any failure. No retries —
    a retry is a second billed call, and a failed episode
    charges nothing beyond the calls already recorded."""
    _vv = _valid_voice(voice)
    if _vv.startswith("voice:"):
        # Generator 7f: cloned voices synthesize on the
        # ElevenLabs rails (og_voice_lab), never via OpenAI.
        try:
            import og_voice_lab as _vl
        except Exception:
            raise _TTSError("auth", "the voice lab is unavailable")
        if not _vl.enabled():
            raise _TTSError(
                "auth", "the voice lab is not switched on")
        try:
            data = _vl._run_cloned_tts(
                _vv[len("voice:"):], str(text)[:_TTS_MAX_CHARS])
        except Exception as e:
            kind = getattr(e, "kind", "http")
            raise _TTSError(
                kind if kind in _FAIL_DETAILS else "http",
                f"cloned voice service failed: {e}")
        if len(data) < 100:
            raise _TTSError(
                "bad_audio",
                f"cloned voice service sent {len(data)} bytes")
        return data
    import httpx
    key = _api_key()
    if not key:
        raise _TTSError("auth", "no voice key configured")
    voice = _valid_voice(voice) or DEFAULT_VOICES[0]
    try:
        with httpx.Client(timeout=90) as client:
            r = client.post(
                "https://api.openai.com/v1/audio/speech",
                headers={"Authorization": f"Bearer {key}"},
                json={"model": _TTS_MODEL, "voice": voice,
                      "input": str(text)[:_TTS_MAX_CHARS],
                      "response_format": "mp3"})
    except Exception as e:
        raise _TTSError("network", f"voice service unreachable: {e}")
    if r.status_code != 200:
        kind = "auth" if r.status_code in (401, 403) else \
            "rate" if r.status_code == 429 else "http"
        raise _TTSError(
            kind, f"voice service answered {r.status_code}: "
                  f"{(r.text or '')[:160]}")
    data = r.content or b""
    if len(data) < 100:
        raise _TTSError("bad_audio",
                        f"voice service sent {len(data)} bytes")
    return data


