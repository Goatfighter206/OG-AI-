"""
OG podcasts (Generator 7a) — OG drafts a TWO-HOST podcast script
in chat, the visitor approves the script, and OG voices it line
by line on the existing TTS rails into one stitched MP3:
in-chat player, owner-only download, locker save, Library.

The flow (Brent's prepare -> approve -> execute rule, the
Round 28 video / Round 30 song shape):

1. ASK. "make a podcast about X" (also "podcast episode on X",
   "turn this into a podcast", "I want a podcast about X")
   claims a podcast job. The reply makes the agent WRITE THE
   SCRIPT in the thread — a TITLE line, an optional HOSTS line,
   and alternating "HOST 1:" / "HOST 2:" lines — and end with
   the approval ask. Default voices are onyx (Host 1) + nova
   (Host 2); the visitor can name any voices from the /tts
   table (app.py TTS_VOICES: onyx, fable, echo, nova, shimmer,
   alloy) in the ask or on the HOSTS line; an invalid name
   falls back to the defaults. Script target is ~450-900 words
   (~3-6 minutes at a 150 wpm spoken pace) unless the visitor
   asks shorter / longer / N minutes. A per-visitor pending is
   parked (30-min expiry). NO TTS call happens before approval
   — zero provider spend pre-YES.
2. APPROVE. Chat YES / NO, or the on-page card (GET
   /podcast/status carries the pending with the REAL title,
   line count, estimated minutes, voices, and a preview of the
   script's first lines — captured from the visitor's own
   history, the "what was shown is what ships" pattern; POST
   /podcast/approve and /podcast/decline are the card's doors).
   First resolution wins; a decline scraps the pending and
   spends nothing. Script edits ("make host 2 funnier") loop
   back to a fresh draft.
3. GENERATE. On approval a background job synthesizes the
   script line by line: each line is chunked to the /tts
   600-char input limit (og_video.split_tts_chunks), each chunk
   is ONE TTS call in the host's voice through the same OpenAI
   speech endpoint /tts and og_video use, and the parts are
   stitched with ffmpeg (0.35 s of silence between lines) into
   one MP3. The output is verified (duration > 0) before the
   job counts as done. Any line's TTS failure fails the whole
   job honestly — no partial episode ships, nothing enters
   the Library, and og_fixqueue.record_problem fires, exactly
   as for video/song failures.
4. DELIVER. Owner-only GET /podcast/download/<id> (24 h
   retention), an inline <audio> player + download button on
   the page when the job completes (static/og_podcast.js card),
   "Save to my locker" (POST /podcast/save/<id>) for tiers with
   quota, a Library item of kind "podcast", and a
   podcast_done notification (target {"view": "library",
   "kind": "podcast", "id": ...}, the Round 59 shape).

CAPS — the honest accounting (no new priced kind is invented):
- The script draft costs ONE chat call: it is generated by the
  /chat turn that carries this module's instruction, and
  app.py's own _record_chat_usage charges that turn exactly
  once against the weekly chat pool (Round 55). This module
  never double-charges a draft.
- Every TTS chunk call is recorded in the usage entry
  "tts:<uid>" EXACTLY the way app.py's _consume_tts_call
  records a voice reply (same entry shape, carry_days /
  note_day substrate), at call time — also /tts's posture,
  since its consume happens before the upstream request. The
  job record carries tts_est (the estimate shown at approval),
  tts_calls (calls actually recorded) and tts_overage.
- MID-JOB POOL EXHAUSTION — THE DECISION: an approved episode
  FINISHES. Approval was given against the estimate shown in
  the ask, so if the weekly tts pool runs dry mid-episode the
  remaining lines are still synthesized and recorded (the
  entry honestly exceeds the weekly cap, and ordinary /tts
  voice replies sit at the wall until days roll off). Token
  packs are NOT debited for podcast calls. This is the one
  deliberate divergence from /tts's 429-at-the-wall, and it
  applies only inside an approved podcast job.

DARK GATE: podcasts are live only when an OpenAI key is
configured AND an ffmpeg binary exists (og_video.enabled's
exact conditions — podcasts ride the same rails). Dark =
claims never fire, /podcast/status answers {"enabled": false},
the card doors 404.

Job records ride the og_songs store pattern: Postgres table
og_podcast_jobs when OG_MEMORY_DB_URL is set, else a JSON
file beside the builds. Pending approvals are process-local:
a restart mid-window drops the pending — nothing was
generated, the visitor just asks again. Episodes live on
local disk (the locker is the durable home, via Save).

Persona files are NEVER touched by this module. Scripts come
from the existing persona, in the thread, like every other
generator's drafts.
"""

