# --- Pending approvals (process-local, the Round 28/30 shape) --------------------


_pending: Dict[str, Dict] = {}
_pending_lock = threading.Lock()


def _set_pending(uid: str, state: Dict):
    state = dict(state)
    state.setdefault("created", time.time())
    with _pending_lock:
        _pending[uid] = state


def _get_pending(uid: str) -> Optional[Dict]:
    if not uid:
        return None
    with _pending_lock:
        state = _pending.get(uid)
        if state and time.time() - float(state.get("created", 0)) \
                > _PENDING_TTL:
            del _pending[uid]
            return None
        return dict(state) if state else None


def _clear_pending(uid: str):
    with _pending_lock:
        _pending.pop(uid, None)


# --- Job records (Postgres when OG_MEMORY_DB_URL, else JSON) ---------------------

MEMORY_DB_URL = os.getenv("OG_MEMORY_DB_URL", "").strip()
from og_db import DB_CONNECT_TIMEOUT as _DB_CT, apply_bounds as _apply_bounds
try:
    import psycopg
    from psycopg.types.json import Jsonb as _Jsonb
except Exception:  # psycopg missing — JSON backend is used
    psycopg = None

_jobs_lock = threading.Lock()
_jobs_mem: Dict[str, Dict] = {}
_gen_slots = threading.Semaphore(2)


def _key(uid: str) -> str:
    return hashlib.sha256(str(uid).encode()).hexdigest()[:32]


def _json_store_path() -> str:
    os.makedirs(STORE_DIR, exist_ok=True)
    return os.path.join(STORE_DIR, "podcast_jobs.json")


def _db_connect():
    conn = psycopg.connect(MEMORY_DB_URL, connect_timeout=_DB_CT)
    _apply_bounds(conn)
    with conn.cursor() as cur:
        cur.execute(
            "CREATE TABLE IF NOT EXISTS og_podcast_jobs ("
            "id TEXT PRIMARY KEY, owner TEXT, updated DOUBLE PRECISION,"
            " data TEXT)")
    conn.commit()
    return conn


def _store_put(rec: Dict) -> None:
    rec = dict(rec)
    rec["updated"] = time.time()
    with _jobs_lock:
        _jobs_mem[rec["id"]] = rec
    if MEMORY_DB_URL and psycopg is not None:
        try:
            with _db_connect() as conn:
                with conn.cursor() as cur:
                    cur.execute(
                        "INSERT INTO og_podcast_jobs (id, owner, updated,"
                        " data) VALUES (%s, %s, %s, %s) ON CONFLICT"
                        " (id) DO UPDATE SET owner = EXCLUDED.owner,"
                        " updated = EXCLUDED.updated,"
                        " data = EXCLUDED.data",
                        (rec["id"], rec.get("owner", ""), rec["updated"],
                         json.dumps(rec)))
                conn.commit()
            return
        except Exception as e:
            logger.warning(f"Podcast job DB write failed: {e}")
    try:
        path = _json_store_path()
        data = {}
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f) or {}
        data[rec["id"]] = rec
        cutoff = time.time() - _JOB_TTL
        data = {k: v for k, v in data.items()
                if float(v.get("updated", 0)) > cutoff}
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f)
    except Exception as e:
        logger.warning(f"Podcast job JSON write failed: {e}")


def _store_get(job_id: str) -> Optional[Dict]:
    with _jobs_lock:
        rec = _jobs_mem.get(job_id)
    if rec:
        return dict(rec)
    if MEMORY_DB_URL and psycopg is not None:
        try:
            with _db_connect() as conn:
                with conn.cursor() as cur:
                    cur.execute(
                        "SELECT data FROM og_podcast_jobs WHERE id = %s",
                        (job_id,))
                    row = cur.fetchone()
            if row:
                rec = json.loads(row[0])
                with _jobs_lock:
                    _jobs_mem[job_id] = rec
                return dict(rec)
        except Exception as e:
            logger.warning(f"Podcast job DB read failed: {e}")
    try:
        path = _json_store_path()
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f) or {}
            rec = data.get(job_id)
            if rec:
                with _jobs_lock:
                    _jobs_mem[job_id] = rec
                return dict(rec)
    except Exception as e:
        logger.warning(f"Podcast job JSON read failed: {e}")
    return None


def _store_latest_for_owner(owner: str) -> Optional[Dict]:
    best = None
    with _jobs_lock:
        cands = [dict(r) for r in _jobs_mem.values()
                 if r.get("owner") == owner]
    if MEMORY_DB_URL and psycopg is not None:
        try:
            with _db_connect() as conn:
                with conn.cursor() as cur:
                    cur.execute(
                        "SELECT data FROM og_podcast_jobs WHERE owner"
                        " = %s ORDER BY updated DESC LIMIT 1",
                        (owner,))
                    row = cur.fetchone()
            if row:
                cands.append(json.loads(row[0]))
        except Exception as e:
            logger.warning(f"Podcast job DB scan failed: {e}")
    try:
        path = _json_store_path()
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f) or {}
            cands.extend(v for v in data.values()
                         if v.get("owner") == owner)
    except Exception as e:
        logger.warning(f"Podcast job JSON scan failed: {e}")
    for rec in cands:
        if best is None or float(rec.get("updated", 0)) \
                > float(best.get("updated", 0)):
            best = rec
    return best


def list_jobs_for_owner(uid: str) -> List[Dict]:
    """All of the visitor's OWN podcast jobs, newest first
    (Library). Read-only — retention is NOT re-decided here;
    the caller passes each record through _job_view, which
    hides stale/gone jobs exactly as /podcast/status does."""
    owner = _key(uid)
    found: Dict[str, Dict] = {}
    with _jobs_lock:
        for r in _jobs_mem.values():
            if r.get("owner") == owner:
                found[r["id"]] = dict(r)
    if MEMORY_DB_URL and psycopg is not None:
        try:
            with _db_connect() as conn:
                with conn.cursor() as cur:
                    cur.execute(
                        "SELECT data FROM og_podcast_jobs WHERE owner"
                        " = %s", (owner,))
                    rows = cur.fetchall()
            for row in rows:
                rec = json.loads(row[0])
                found[rec["id"]] = rec
        except Exception as e:
            logger.warning(f"Podcast job DB list failed: {e}")
    try:
        path = _json_store_path()
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f) or {}
            for v in data.values():
                if v.get("owner") == owner:
                    found[v["id"]] = v
    except Exception as e:
        logger.warning(f"Podcast job JSON list failed: {e}")
    return sorted(found.values(),
                  key=lambda r: float(r.get("created", 0)),
                  reverse=True)


def purge_owner(uid: str):
    """Account deletion (Round 36, og_store_ready): every
    podcast job this visitor owns — memory, DB rows, JSON
    fallback and build dirs — plus any pending draft. Other
    owners' jobs are never touched."""
    if not uid:
        return
    _clear_pending(uid)
    owner = _key(uid)
    ids = [r["id"] for r in list_jobs_for_owner(uid)]
    if ids:
        with _jobs_lock:
            for jid in ids:
                _jobs_mem.pop(jid, None)
    if MEMORY_DB_URL and psycopg is not None:
        try:
            with _db_connect() as conn:
                with conn.cursor() as cur:
                    cur.execute(
                        "DELETE FROM og_podcast_jobs WHERE owner = %s",
                        (owner,))
                conn.commit()
        except Exception as e:
            logger.warning(f"Podcast job DB purge failed: {e}")
    try:
        path = _json_store_path()
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f) or {}
            kept = {k: v for k, v in data.items()
                    if v.get("owner") != owner}
            if len(kept) != len(data):
                with open(path, "w", encoding="utf-8") as f:
                    json.dump(kept, f)
    except Exception as e:
        logger.warning(f"Podcast job JSON purge failed: {e}")
    import shutil
    for jid in ids:
        try:
            shutil.rmtree(os.path.join(STORE_DIR, jid),
                          ignore_errors=True)
        except Exception:
            pass


def _active_job(uid: str) -> Optional[Dict]:
    rec = _store_latest_for_owner(_key(uid))
    if rec and rec.get("state") in ("queued", "generating"):
        if time.time() - float(rec.get("updated", 0)) > _STALE_S:
            return None     # stale working record = a cut-off take
        return rec
    return None


# --- Script parsing -----------------------------------------------------------------


_TITLE_RE = re.compile(
    r"^\s*(?:#{1,3}\s*)?(?:\*\*)?TITLE\s*[:\-—]\s*(.+?)(?:\*\*)?\s*$",
    re.IGNORECASE)
_HOSTS_RE = re.compile(
    r"^\s*(?:#{1,3}\s*)?(?:\*\*)?HOSTS?\s*[:\-—]\s*(.+?)(?:\*\*)?\s*$",
    re.IGNORECASE)
_LINE_RE = re.compile(
    r"^\s*(?:\*\*|__)?\s*HOST\s*([12])\s*(?:\*\*|__)?\s*"
    r"[:\-—]\s*(.+?)\s*$", re.IGNORECASE)


def _clean_text(text: str) -> str:
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text or "")
    text = re.sub(r"(?m)^#{1,4}\s*", "", text)
    text = text.replace("`", "")
    return text.strip()


def _word_count(text: str) -> int:
    return len([w for w in re.split(r"\s+", text or "") if w])


def _valid_voice(name) -> str:
    raw = str(name or "").strip()
    low = raw.lower()
    if low in TTS_VOICES:
        return low
    # Generator 7f: a cloned voice rides as `voice:<voice_id>`
    # (case preserved — provider ids are case-sensitive).
    # Ownership is checked in the job runner, where uid lives;
    # synthesis delegates to og_voice_lab's ElevenLabs seam.
    if re.fullmatch(r"voice:[A-Za-z0-9_\-]{4,80}", raw):
        return raw
    return ""


def _voices_from_text(text: str) -> List[str]:
    """Valid TTS voice names in order of appearance in `text`
    (deduplicated). Invalid names simply never appear here —
    callers fall back to the defaults for any unfilled slot."""
    found: List[str] = []
    for m in re.finditer(r"\b(onyx|fable|echo|nova|shimmer|alloy)\b",
                         str(text or "").lower()):
        if m.group(1) not in found:
            found.append(m.group(1))
    return found


def resolve_voices(*sources) -> List[str]:
    """[host1_voice, host2_voice] from the first sources that
    supply valid names, in priority order; any slot still empty
    takes the defaults (onyx, nova), and the two hosts never
    share a voice unless a source named the same one twice —
    in that case host 2 falls back to the other default."""
    picks: List[str] = []
    for src in sources:
        if not src:
            continue
        if isinstance(src, (list, tuple)):
            candidates = [_valid_voice(v) for v in src]
        else:
            candidates = _voices_from_text(str(src))
        for v in candidates:
            if v and v not in picks:
                picks.append(v)
        if len(picks) >= 2:
            break
    out = [picks[0] if len(picks) > 0 else DEFAULT_VOICES[0],
           picks[1] if len(picks) > 1 else DEFAULT_VOICES[1]]
    if out[0] == out[1]:
        out[1] = (DEFAULT_VOICES[1] if out[0] != DEFAULT_VOICES[1]
                  else DEFAULT_VOICES[0])
    return out


def parse_podcast_script(text: str, voices=None) -> Optional[Dict]:
    """Parse a two-host podcast script out of an assistant
    message: a TITLE line, an optional HOSTS line, and
    HOST 1: / HOST 2: lines. Consecutive lines from the same
    host are merged, so the delivered lines strictly alternate.
    Voice priority: `voices` (the visitor's own ask) > the
    HOSTS line > defaults. Returns {title, lines, words,
    voices} or None when the text isn't a podcast script (one
    host missing, too few lines, too little said)."""
    if not text:
        return None
    lines_in = str(text).splitlines()
    title = ""
    hosts_line = ""
    body: List = []
    for line in lines_in:
        m = _TITLE_RE.match(line)
        if m and not title:
            title = m.group(1).strip().strip("*").strip()
            continue
        m = _HOSTS_RE.match(line)
        if m and not hosts_line and not body:
            hosts_line = m.group(1)
            continue
        body.append(line)
    merged: List[Dict] = []
    for line in body:
        m = _LINE_RE.match(line)
        if not m:
            continue
        host = int(m.group(1))
        clean = _clean_text(m.group(2))
        if not clean:
            continue
        if merged and merged[-1]["host"] == host:
            merged[-1]["text"] = (merged[-1]["text"] + " " + clean)
        else:
            merged.append({"host": host, "text": clean})
    # Trim trailing non-script lines off the last host line: the
    # approval ask the persona appends is prose in the reply,
    # never behind a HOST marker, but a long closing ramble
    # inside the last line is not script either.
    hosts_seen = {ln["host"] for ln in merged}
    if hosts_seen != {1, 2} or len(merged) < _MIN_LINES:
        return None
    words = sum(_word_count(ln["text"]) for ln in merged)
    if words < _MIN_WORDS:
        return None
    while len(merged) > _MIN_LINES and words > _MAX_WORDS:
        dropped = merged.pop()
        words -= _word_count(dropped["text"])
        if {ln["host"] for ln in merged} != {1, 2}:
            merged.append(dropped)
            words += _word_count(dropped["text"])
            break
    title = title.strip().strip('"“”').strip() or "OG's Podcast"
    v = resolve_voices(voices, hosts_line)
    for ln in merged:
        ln["voice"] = v[ln["host"] - 1]
    return {"title": title[:90], "lines": merged, "words": words,
            "voices": v}


def _est_min(words: int) -> float:
    return round(words / float(_WPM), 1)


def split_line(text: str) -> List[str]:
    """Chunk one script line to the /tts 600-char input limit
    (og_video's sentence chunker, reused)."""
    import og_video as _video
    return _video.split_tts_chunks(text, limit=_TTS_MAX_CHARS)


def estimate_tts_calls(script: Dict) -> int:
    """The approval-time estimate: one TTS call per <=600-char
    chunk of every line."""
    return sum(max(1, len(split_line(ln["text"])))
               for ln in script.get("lines", []))


# --- History capture (what was shown is what ships) ---------------------------------


def _history(uid: str) -> List[Dict]:
    fn = _dep("load_history")
    if fn is None:
        return []
    try:
        return fn(uid) or []
    except Exception as e:
        logger.warning(f"Podcast history read failed: {e}")
        return []


def _capture_from_history(uid: str, pending: Dict) -> Optional[Dict]:
    hist = _history(uid)
    start = int(pending.get("hist_len", 0))
    voices = pending.get("voices")
    for entry in reversed(hist[start:]):
        if not isinstance(entry, dict) \
                or entry.get("role") != "assistant":
            continue
        parsed = parse_podcast_script(str(entry.get("content", "")),
                                      voices)
        if parsed:
            return parsed
    if pending.get("stage") == "await_approval":
        for entry in reversed(hist):
            if not isinstance(entry, dict) \
                    or entry.get("role") != "assistant":
                continue
            parsed = parse_podcast_script(
                str(entry.get("content", "")), voices)
            if parsed:
                return parsed
    return None


def _ensure_captured(uid: str, pending: Dict) -> Optional[Dict]:
    if pending.get("lines"):
        return pending
    parsed = _capture_from_history(uid, pending)
    if not parsed:
        return None
    pending = dict(pending)
    pending.update({
        "stage": "await_approval",
        "title": parsed["title"], "lines": parsed["lines"],
        "words": parsed["words"], "voices": parsed["voices"]})
    _set_pending(uid, pending)
    return pending


