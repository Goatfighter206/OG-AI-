# --- Claim table ------------------------------------------------------------------------


_YES_WORDS = {
    "yes", "yeah", "yep", "yup", "ya", "ok", "okay", "sure",
    "approve", "approved", "go", "do it", "make it", "lets go",
    "let's go", "yes please", "yes make it", "yes do it",
    "record it", "voice it", "make the podcast", "👍",
}
_NO_WORDS = {
    "no", "nope", "nah", "decline", "declined", "scrap it",
    "never mind", "nevermind", "forget it", "cancel", "stop",
    "don't", "dont", "no thanks",
}
_POD_VERB = re.compile(
    r"\b(make|create|record|generate|produce|start|cut)\b", re.I)
_POD_NOUN = re.compile(r"\bpodcasts?\b", re.I)
_POD_ON = re.compile(
    r"\bpodcast(?:\s+episode)?\s+(?:about|on)\s+(.+)$", re.I)
_ABOUT = re.compile(r"\b(?:about|on)\s+(.+)$", re.I)
_WANT_POD = re.compile(
    r"\bi want\s+(?:a\s+|an\s+)?podcast\b", re.I)
_THREAD_BIND = re.compile(
    r"\b(turn|make)\b[^.?!]{0,40}\b(that|this|it)\b"
    r"[^.?!]{0,20}\bpodcast\b|\bturn that into a podcast\b|"
    r"\bmake that a podcast\b|\bpodcast of that\b", re.I)
_MINUTES = re.compile(r"\b(\d{1,3})\s*(?:minutes?|mins?)\b", re.I)


def _norm(message: str) -> str:
    return " ".join(str(message or "").lower().split()).strip(" .!")


def _length_hint(raw: str) -> int:
    """Target script words from the ask: 'N minutes' wins, then
    short / long, else the 450-900 default's midpoint."""
    m = _MINUTES.search(raw or "")
    if m:
        return max(150, min(2250, int(m.group(1)) * _WPM))
    low = str(raw or "").lower()
    if re.search(r"\bshort\b|\bquick\b|\bbrief\b", low):
        return 300
    if re.search(r"\blong\b|\blonger\b|\bdeep dive\b", low):
        return 1200
    return _DEFAULT_WORDS


def _clean_topic(topic: str) -> str:
    topic = str(topic or "").strip().strip(".!")
    # A trailing voice clause ("... with onyx and nova voices")
    # is casting, not topic.
    topic = re.sub(r"\s+with\s+[^.]{0,60}?\bvoices?\b.*$", "",
                   topic, flags=re.I).strip()
    return topic[:200]


def _browser_has_pending(uid: str) -> bool:
    """A bare YES/NO owed to a parked browser action is never
    stolen (the Round 21/27 rule, as in og_songs)."""
    try:
        import og_browser as _browser
        pend = _browser._get_pending(uid)
        return bool(pend and pend.get("kind") == "action")
    except Exception:
        return False


def _other_pending_newer(uid: str, podcast_pending: Dict) -> bool:
    """When a story-video or song approval is ALSO parked, the
    bare YES/NO belongs to whichever ask the visitor saw LAST
    (the newest pending) — the og_songs cross-module rule."""
    try:
        created = float(podcast_pending.get("created", 0))
        import og_video as _video
        vpend = _video._get_pending(uid)
        if vpend and float(vpend.get("created", 0)) > created:
            return True
        import og_songs as _songs
        spend = _songs._get_pending(uid)
        if spend and float(spend.get("created", 0)) > created:
            return True
    except Exception:
        pass
    return False


def _claim_podcast(message: str, uid: str) -> Optional[Dict]:
    if not uid or not enabled():
        return None
    raw = str(message or "")
    low = raw.lower()
    norm = _norm(raw)
    pending = _get_pending(uid)
    if pending is not None:
        stage = pending.get("stage", "")
        if stage == "await_topic":
            if norm in _NO_WORDS:
                return {"kind": "decline"}
            m = _ABOUT.search(raw.strip())
            if _POD_NOUN.search(low) and m:
                return {"kind": "topic",
                        "topic": _clean_topic(m.group(1)),
                        "voices": _voices_from_text(raw),
                        "target_words": _length_hint(raw)}
            if len(norm) >= 2:
                return {"kind": "topic",
                        "topic": _clean_topic(raw),
                        "voices": _voices_from_text(raw),
                        "target_words": _length_hint(raw)}
            return None
        # A fresh ask with its own topic replaces the parked
        # draft instead of approving it by accident.
        if _POD_NOUN.search(low) and _ABOUT.search(raw):
            m = _ABOUT.search(raw.strip())
            return {"kind": "replace",
                    "topic": _clean_topic(m.group(1)),
                    "voices": _voices_from_text(raw),
                    "target_words": _length_hint(raw)}
        if norm in _YES_WORDS:
            if _browser_has_pending(uid):
                return None
            if _other_pending_newer(uid, pending):
                return None
            return {"kind": "approve"}
        if norm in _NO_WORDS:
            if _browser_has_pending(uid):
                return None
            if _other_pending_newer(uid, pending):
                return None
            return {"kind": "decline"}
        if re.search(r"\b(change|rewrite|redo|make it|instead|"
                     r"add|remove|funnier|serious|longer|shorter|"
                     r"host|voice|swap)\b", low) and len(low) < 300:
            return {"kind": "revise", "note": raw.strip()[:300]}
        return None
    # No pending — bare approvals/declines claim nothing.
    if _THREAD_BIND.search(low) and not _ABOUT.search(raw):
        return {"kind": "from_thread",
                "voices": _voices_from_text(raw),
                "target_words": _length_hint(raw)}
    m = _POD_ON.search(raw.strip())
    if m:
        return {"kind": "new", "topic": _clean_topic(m.group(1)),
                "voices": _voices_from_text(raw),
                "target_words": _length_hint(raw)}
    verb = _POD_VERB.search(low)
    noun = _POD_NOUN.search(low)
    want = _WANT_POD.search(low)
    vpos = verb.start() if verb else (want.start() if want else None)
    if noun and vpos is not None and noun.start() > vpos \
            and noun.start() - vpos < 60:
        topic = ""
        m2 = _ABOUT.search(raw.strip())
        if m2:
            topic = _clean_topic(m2.group(1))
        return {"kind": "new", "topic": topic,
                "voices": _voices_from_text(raw),
                "target_words": _length_hint(raw)}
    if _THREAD_BIND.search(low):
        return {"kind": "from_thread",
                "voices": _voices_from_text(raw),
                "target_words": _length_hint(raw)}
    return None


